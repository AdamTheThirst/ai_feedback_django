"""Сервис ограничения частоты неуспешных попыток входа по email и IP."""

from django.core.cache import cache

MAX_FAILED_ATTEMPTS = 5
BLOCK_SECONDS = 300


def _build_cache_key(email: str, ip_address: str) -> str:
    """Формирует ключ cache для хранения счётчика попыток входа.

    Контекст использования:
        Используется внутренними функциями сервиса rate-limit для изоляции
        попыток по комбинации email и IP-адреса.

    Параметры:
        email: Email, введённый пользователем в форме входа.
        ip_address: IP-адрес источника запроса.

    Возвращаемое значение:
        Строковый ключ для backend кэша.

    Исключения и особые случаи:
        Пустые значения заменяются безопасными маркерами.

    Побочные эффекты:
        Побочные эффекты отсутствуют.
    """

    normalized_email = (email or "unknown").strip().lower()
    normalized_ip = (ip_address or "unknown").strip()
    return f"auth_failed:{normalized_email}:{normalized_ip}"


def is_blocked(email: str, ip_address: str) -> bool:
    """Проверяет, заблокированы ли попытки входа для пары email+IP.

    Контекст использования:
        Вызывается перед аутентификацией для быстрой защиты от перебора
        без запуска дорогой проверки пароля в каждом запросе.

    Параметры:
        email: Email из формы входа.
        ip_address: IP-адрес клиента.

    Возвращаемое значение:
        ``True``, если лимит исчерпан; иначе ``False``.

    Исключения и особые случаи:
        При отсутствии записи в кэше считается, что блокировки нет.

    Побочные эффекты:
        Побочные эффекты отсутствуют.
    """

    attempts = cache.get(_build_cache_key(email=email, ip_address=ip_address), 0)
    return attempts >= MAX_FAILED_ATTEMPTS


def register_failed_attempt(email: str, ip_address: str) -> int:
    """Увеличивает счётчик неуспешных попыток входа.

    Контекст использования:
        Вызывается после неудачной аутентификации для накопления событий
        и последующей краткосрочной блокировки входа.

    Параметры:
        email: Email из формы входа.
        ip_address: IP-адрес клиента.

    Возвращаемое значение:
        Текущее значение счётчика после увеличения.

    Исключения и особые случаи:
        Если ключ отсутствовал, счётчик создаётся со значением ``1``.

    Побочные эффекты:
        Обновляет данные в backend-кэше на период ``BLOCK_SECONDS``.
    """

    key = _build_cache_key(email=email, ip_address=ip_address)
    attempts = cache.get(key, 0) + 1
    cache.set(key, attempts, BLOCK_SECONDS)
    return attempts


def reset_failed_attempts(email: str, ip_address: str) -> None:
    """Сбрасывает счётчик неуспешных входов после успешной авторизации.

    Контекст использования:
        Используется при корректном входе, чтобы не держать пользователя
        в ложной блокировке после успешного подтверждения пароля.

    Параметры:
        email: Email из формы входа.
        ip_address: IP-адрес клиента.

    Возвращаемое значение:
        Ничего не возвращает.

    Исключения и особые случаи:
        Удаление отсутствующего ключа безопасно и не вызывает ошибок.

    Побочные эффекты:
        Удаляет запись счётчика в backend-кэше.
    """

    cache.delete(_build_cache_key(email=email, ip_address=ip_address))
