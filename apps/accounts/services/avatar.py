"""Сервисные функции генерации буквенного аватара и детерминированного фона."""

import hashlib

LIGHT_AVATAR_PALETTE: tuple[str, ...] = (
    "#F7D6D0",
    "#FDE2C8",
    "#F8EFB7",
    "#D9F2C4",
    "#CDEEEA",
    "#D7E7FB",
    "#E2DBFB",
    "#F3D9EE",
)


def build_avatar_letter(nickname: str) -> str:
    """Возвращает первую букву никнейма для отображаемого аватара.

    Контекст использования:
        Применяется при регистрации пользователя и возможном обновлении никнейма,
        чтобы интерфейс показывал стабильную буквенную иконку профиля.

    Параметры:
        nickname: Исходный никнейм пользователя.

    Возвращаемое значение:
        Одна заглавная буква; если никнейм пустой после нормализации — ``?``.

    Исключения и особые случаи:
        Пустая или пробельная строка обрабатывается без исключения.

    Побочные эффекты:
        Побочные эффекты отсутствуют.
    """

    normalized = (nickname or "").strip()
    if not normalized:
        return "?"
    return normalized[0].upper()


def build_avatar_bg_hex(seed_value: str) -> str:
    """Возвращает детерминированный цвет из безопасной светлой палитры.

    Контекст использования:
        Нужен для стабильно узнаваемого фона буквенного аватара пользователя,
        соответствующего UX-требованиям проекта.

    Параметры:
        seed_value: Строка-источник детерминированного выбора цвета
            (например email пользователя).

    Возвращаемое значение:
        HEX-цвет из фиксированной светлой палитры.

    Исключения и особые случаи:
        При пустом seed-значении используется первый цвет палитры.

    Побочные эффекты:
        Побочные эффекты отсутствуют.
    """

    normalized = (seed_value or "").strip().lower()
    if not normalized:
        return LIGHT_AVATAR_PALETTE[0]
    digest = hashlib.sha256(normalized.encode("utf-8")).hexdigest()
    index = int(digest[:8], 16) % len(LIGHT_AVATAR_PALETTE)
    return LIGHT_AVATAR_PALETTE[index]
