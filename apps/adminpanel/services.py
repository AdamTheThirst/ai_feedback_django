"""Сервисы проверки ролей и владения объектами для внутренней админ-панели."""

from typing import Any

from django.db.models import Model, QuerySet

from apps.accounts.models import User, UserRole


def user_can_access_backoffice(user: User) -> bool:
    """Проверяет доступ пользователя к внутренней административной панели.

    Контекст использования:
        Используется во view/mixin бэкофиса для блокировки обычных пользователей.

    Параметры:
        user: Текущий пользователь из ``request.user``.

    Возвращаемое значение:
        ``True`` для ролей ``admin`` и ``superadmin``; иначе ``False``.

    Исключения и особые случаи:
        Неаутентифицированный пользователь всегда считается недопустимым.

    Побочные эффекты:
        Побочные эффекты отсутствуют.
    """

    return bool(user.is_authenticated and user.role in {UserRole.ADMIN, UserRole.SUPERADMIN})


def is_superadmin(user: User) -> bool:
    """Проверяет, относится ли пользователь к уровню супер-администратора.

    Контекст использования:
        Нужен для разрешения глобального доступа к объектам в бэкофисе.

    Параметры:
        user: Текущий пользователь.

    Возвращаемое значение:
        ``True`` при роли ``superadmin``, иначе ``False``.

    Исключения и особые случаи:
        Особые исключения отсутствуют.

    Побочные эффекты:
        Побочные эффекты отсутствуют.
    """

    return bool(user.is_authenticated and user.role == UserRole.SUPERADMIN)


def filter_owned_queryset(queryset: QuerySet, user: User) -> QuerySet:
    """Ограничивает queryset объектами пользователя-администратора.

    Контекст использования:
        Применяется в списках и операциях изменения для enforce-прав владения.

    Параметры:
        queryset: Исходный queryset контентной модели.
        user: Текущий пользователь.

    Возвращаемое значение:
        Полный queryset для супер-админа или отфильтрованный по владельцу набор.

    Исключения и особые случаи:
        Для моделей без ``created_by`` требуется отдельная обработка выше уровнем.

    Побочные эффекты:
        Побочные эффекты отсутствуют.
    """

    if is_superadmin(user):
        return queryset
    return queryset.filter(created_by=user)


def user_can_manage_object(user: User, obj: Model, owner_field_name: str = "created_by") -> bool:
    """Проверяет право пользователя изменять конкретный объект.

    Контекст использования:
        Используется в update/archive-операциях для серверной валидации прав,
        независимо от того, что показано в интерфейсе.

    Параметры:
        user: Текущий пользователь.
        obj: Экземпляр модели, над которым выполняется действие.
        owner_field_name: Название поля владельца объекта.

    Возвращаемое значение:
        ``True``, если пользователь имеет право изменения объекта.

    Исключения и особые случаи:
        Если у объекта нет указанного поля владельца, возвращается ``False``.

    Побочные эффекты:
        Побочные эффекты отсутствуют.
    """

    if not user_can_access_backoffice(user):
        return False
    if is_superadmin(user):
        return True

    if not hasattr(obj, owner_field_name):
        return False
    return getattr(obj, owner_field_name) == user


def build_backoffice_stats(models_map: dict[str, type[Model]]) -> dict[str, Any]:
    """Собирает краткую сводку для дашборда административной панели.

    Контекст использования:
        Применяется на странице ``/backoffice/`` для быстрого обзора состояния
        контента и связанных технических сущностей.

    Параметры:
        models_map: Словарь вида ``{ключ: модель}`` для подсчёта записей.

    Возвращаемое значение:
        Словарь ``{ключ: количество}`` для рендера в шаблоне.

    Исключения и особые случаи:
        Ошибки подсчёта не обрабатываются на этом уровне.

    Побочные эффекты:
        Выполняет SQL-запросы ``COUNT`` к переданным моделям.
    """

    return {key: model.objects.count() for key, model in models_map.items()}
