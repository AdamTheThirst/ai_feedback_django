"""Общие абстрактные модели для переиспользования в предметных приложениях."""

import uuid

from django.conf import settings
from django.db import models


class TimestampedModel(models.Model):
    """Добавляет стандартные служебные временные поля создания и изменения записи.

    Контекст использования:
        Применяется как базовый миксин почти для всех предметных сущностей,
        чтобы единообразно хранить временные метки жизненного цикла записи.

    Параметры:
        Явных параметров не принимает. Поля автоматически обслуживаются ORM.

    Возвращаемое значение:
        Экземпляр конкретной модели-наследника с полями ``created_at`` и ``updated_at``.

    Исключения и особые случаи:
        Особые исключения отсутствуют, поведение определяется стандартной ORM Django.

    Побочные эффекты:
        При каждом сохранении экземпляра автоматически обновляется ``updated_at``.
    """

    created_at = models.DateTimeField(auto_now_add=True, verbose_name="Создано")
    updated_at = models.DateTimeField(auto_now=True, verbose_name="Обновлено")

    class Meta:
        """Служебные параметры абстрактной модели времени."""

        abstract = True


class UUIDPublicIdModel(models.Model):
    """Добавляет внешний стабильный UUID-идентификатор для ссылок и интеграций.

    Контекст использования:
        Используется в сущностях, которые должны иметь стабильный идентификатор,
        не зависящий от внутреннего целочисленного первичного ключа.

    Параметры:
        Явных параметров не принимает.

    Возвращаемое значение:
        Экземпляр конкретной модели-наследника с заполненным полем ``public_id``.

    Исключения и особые случаи:
        Конфликты UUID крайне маловероятны и дополнительно ограничены уникальностью.

    Побочные эффекты:
        При создании записи генерируется новый UUID4.
    """

    public_id = models.UUIDField(
        default=uuid.uuid4,
        editable=False,
        unique=True,
        verbose_name="Публичный ID",
    )

    class Meta:
        """Служебные параметры абстрактной модели публичного идентификатора."""

        abstract = True


class ArchivableModel(models.Model):
    """Добавляет поля архивирования для мягкого вывода записи из активного использования.

    Контекст использования:
        Применяется к мастер-данным, которые нельзя удалять физически из-за
        необходимости сохранять историческую консистентность диалогов и отчётов.

    Параметры:
        Явных параметров не принимает.

    Возвращаемое значение:
        Экземпляр конкретной модели-наследника с полями архивного состояния.

    Исключения и особые случаи:
        Сам класс не навязывает бизнес-валидацию момента архивирования.

    Побочные эффекты:
        Позволяет помечать записи архивными без физического удаления строки.
    """

    is_archived = models.BooleanField(default=False, verbose_name="В архиве")
    archived_at = models.DateTimeField(null=True, blank=True, verbose_name="Архивировано")

    class Meta:
        """Служебные параметры абстрактной модели архивирования."""

        abstract = True


class OwnedModel(models.Model):
    """Добавляет связь с пользователем-создателем для разграничения владения объектом.

    Контекст использования:
        Нужен в контентных и служебных сущностях, где права администратора зависят
        от автора объекта, а удаление автора не должно разрушать историю.

    Параметры:
        Явных параметров не принимает.

    Возвращаемое значение:
        Экземпляр конкретной модели-наследника с полем ``created_by``.

    Исключения и особые случаи:
        Поле допускает ``NULL`` для системно созданных или исторических записей.

    Побочные эффекты:
        При удалении пользователя ссылка очищается через ``SET_NULL``.
    """

    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="%(app_label)s_%(class)s_created_set",
        verbose_name="Создал",
    )

    class Meta:
        """Служебные параметры абстрактной модели владельца."""

        abstract = True
